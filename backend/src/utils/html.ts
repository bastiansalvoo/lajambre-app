// Escapa datos controlados por el usuario antes de interpolarlos en HTML
// servido por el backend (paginas de verificacion, feedback, etc.).
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
